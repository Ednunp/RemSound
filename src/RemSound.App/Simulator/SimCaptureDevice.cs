using NAudio.Wave;
using RemSound.Sender;

namespace RemSound.App.Simulator;

/// <summary>
/// A simulated capture device (2026-09-30, the simulator review's second improvement: the capture side in the loop). Its
/// callbacks come on its own card's timing - period, lateness, clock drift, stalls - and carry the test signal in its own
/// format: any sample rate, one or more channels, float or 16/24/32-bit integer. The sender opens it through the real
/// path (<see cref="CaptureDevicesForTest"/>): one source goes through push mode, several - or a program's own sound -
/// through the mixing engine with its rings, resamplers and drift correctors.
/// </summary>
/// <param name="Card">Its callbacks: Frames is the device's own frames per callback (10 ms at 44.1 kHz is 441).</param>
/// <param name="Tone">Carries the 1 kHz tone (left, or the only channel).</param>
/// <param name="Clicks">Carries the delay clicks (right; not on a one-channel device).</param>
/// <param name="Loopback">An output's own sound rather than an input.</param>
/// <param name="PerApp">One program's sound: always through the mixing engine, as the app has it.</param>
/// <param name="LockedToDevice">The sound is made on the device's own clock (a program playing out of it), so a device
/// running fast plays it fast. Otherwise, as a microphone hears the room, the sound is the real world's, in real time,
/// whatever the device's clock (2026-09-30: generated by sample count, a device 300 ppm fast made its clicks 300 ppm too
/// often, and the mixer's drift correction, doing its job, looked like two sources wandering apart).</param>
internal sealed record SimCaptureDevice(string Name, SimCard Card, int SampleRate = 48000, int Channels = 2, int Bits = 32, bool Float = true,
    bool Tone = true, bool Clicks = true, bool Loopback = false, bool PerApp = false, bool LockedToDevice = false)
{
    public WaveFormat Format => Float ? WaveFormat.CreateIeeeFloatWaveFormat(SampleRate, Channels) : new WaveFormat(SampleRate, Bits, Channels);
    /// <summary>Its clock's true rate: nominal, and off by the card's drift.</summary>
    public double TrueRate => SampleRate * (1 + Card.DriftPpm * 1e-6);
    public double Period => Card.Frames / TrueRate;
}

/// <summary>The device as the capture code sees it: an <see cref="IWaveIn"/> whose data comes when the simulator says.</summary>
internal sealed class SimCaptureInput(SimCaptureDevice device, double reportedLatencyMs) : IWaveIn, CaptureDevicesForTest.IReportsLatency
{
    private bool recording;

    public WaveFormat WaveFormat { get; set; } = device.Format;
    public double ReportedInputLatencyMs => reportedLatencyMs;
    public event EventHandler<WaveInEventArgs>? DataAvailable;
    public event EventHandler<StoppedEventArgs>? RecordingStopped;
    public long Callbacks { get; private set; }

    public void StartRecording() => recording = true;
    public void StopRecording() => recording = false;
    public void Dispose() => recording = false;

    /// <summary>The device dies as a real one does (unplugged, taken): its capture stops with an error.</summary>
    public void Die() => RecordingStopped?.Invoke(this, new StoppedEventArgs(new InvalidOperationException("the simulated device was unplugged")));

    /// <summary>Callback number <paramref name="number"/> (from 1): the <see cref="SimCard.Frames"/> frames the device captured
    /// in the period before it, in the device's format. By number, not by a running count: the callbacks of a stall never
    /// come, and what they would have carried is lost, as with a real device.</summary>
    public void Deliver(int number)
    {
        if (!recording) return;
        Callbacks++;
        var frames = device.Card.Frames;
        var captured = (long)(number - 1) * frames;
        var ch = device.Channels;
        var bytesPerSample = device.Bits / 8;
        var bytes = new byte[frames * ch * bytesPerSample];
        // Samples per second of the sound's own time: the device's nominal rate when the sound is made on its clock, its
        // true rate when the sound is the real world's.
        var rate = device.LockedToDevice ? device.SampleRate : device.TrueRate;
        for (var i = 0; i < frames; i++)
        {
            var n = captured + i;
            var tone = device.Tone ? (float)(Simulation.ToneLevel * Math.Sin(2 * Math.PI * Simulation.ToneHz * n / rate)) : 0f;
            // A click where each half-second of the sound's time begins, as long as one 48 kHz sample: the first device
            // sample of the half-second, and any more inside that length. A click one device sample long was too short at
            // 88 kHz and above to survive the conversion to 48 kHz, and nothing was heard (2026-09-30).
            var halves = n / rate / Simulation.ClickEverySec;
            var into = (halves - Math.Floor(halves)) * Simulation.ClickEverySec;
            var first = n == 0 || Math.Floor(halves) != Math.Floor((n - 1) / rate / Simulation.ClickEverySec);
            var click = device.Clicks && (first || into < 1.0 / Simulation.SampleRate - 1e-9) ? Simulation.ClickLevel : 0f;
            for (var c = 0; c < ch; c++)
            {
                var v = ch == 1 ? tone : c == 0 ? tone : c == 1 ? click : 0f;
                Write(bytes, (i * ch + c) * bytesPerSample, v);
            }
        }
        DataAvailable?.Invoke(this, new WaveInEventArgs(bytes, bytes.Length));
    }

    private void Write(byte[] b, int at, float v)
    {
        if (device.Float) { BitConverter.TryWriteBytes(b.AsSpan(at, 4), v); return; }
        var clamped = Math.Clamp(v, -1f, 1f);
        switch (device.Bits)
        {
            case 16: BitConverter.TryWriteBytes(b.AsSpan(at, 2), (short)Math.Round(clamped * 32767)); break;
            case 24:
                var s24 = (int)Math.Round(clamped * 8388607);
                b[at] = (byte)s24; b[at + 1] = (byte)(s24 >> 8); b[at + 2] = (byte)(s24 >> 16);
                break;
            default: BitConverter.TryWriteBytes(b.AsSpan(at, 4), (int)Math.Round(clamped * 2147483647.0)); break;
        }
    }
}
